import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import { parse, stringify } from "yaml";

import { generateWithCodex, type IdeaGenerator } from "../ideas/codex.ts";
import { buildIdeasPrompt, PROMPT_VERSION } from "../ideas/prompt.ts";
import { parseIdeasResponse } from "../ideas/schema.ts";
import type { Idea } from "../images/schema.ts";
import { DEFAULT_SUITE_DIRECTORY, loadSuite } from "./suite.ts";

const SUITE_HEADER = `# Frozen ideas for image-prompt evaluation rounds. Changing a case's idea changes
# the suite: bump suite_version so results from different versions are not
# compared case by case. See docs/exec-plans/active/image-prompt-evals.md.
`;

export interface ReplaceIdeaArgs {
  book: string;
  idea: string;
  // Why the user rejected the idea, if given; passed to the ideas agent.
  reason: string;
  suiteDirectory?: string;
  registryPath?: string;
  generate?: IdeaGenerator;
  signal?: AbortSignal;
}

// Generates one new idea for the book, puts it in the rejected idea's place in
// the suite, and moves the old case file to retired/ with the reason. Rounds
// already run keep their copy of the old idea in round.yaml.
export async function replaceSuiteIdea(args: ReplaceIdeaArgs): Promise<Idea> {
  const directory = resolve(args.suiteDirectory ?? DEFAULT_SUITE_DIRECTORY);
  const suite = await loadSuite({
    directory,
    ...(args.registryPath ? { registryPath: args.registryPath } : {}),
  });
  const rejected = suite.cases.find(
    (entry) => entry.book.slug === args.book && entry.idea.id === args.idea,
  );

  if (!rejected) {
    throw new Error(`${args.book}/${args.idea} is not in the suite`);
  }

  const siblings = suite.cases.filter((entry) => entry.book.slug === args.book);

  const prompt =
    buildIdeasPrompt({
      title: rejected.book.title,
      author: rejected.book.author,
      slug: rejected.book.slug,
      outputRoot: "unused",
      timeoutSeconds: 600,
      ideaCount: 1,
    }) +
    `\nThis idea replaces one the user rejected. Make it clearly different from all of these ideas, which must not be repeated:\n` +
    siblings
      .map(
        (entry) =>
          `- ${entry.idea.name}: ${entry.idea.composition.slice(0, 300)}`,
      )
      .join("\n") +
    rejectionReason(args.reason) +
    `\nUse an id not already used: ${siblings.map((entry) => entry.idea.id).join(", ")}.\n`;

  const response = await collectResponse(
    (args.generate ?? generateWithCodex)({
      prompt,
      model: undefined,
      ideaCount: 1,
      signal: args.signal ?? new AbortController().signal,
    }),
  );
  const idea = parseIdeasResponse(response, 1).ideas[0];

  if (!idea) {
    throw new Error("The ideas agent returned no idea");
  }

  if (siblings.some((entry) => entry.idea.id === idea.id)) {
    throw new Error(`The ideas agent reused the id '${idea.id}'; try again`);
  }

  // Retire the old case, then write the new one and point the suite at it.
  const today = new Date().toISOString().slice(0, 10);
  const retired = join(directory, "retired", args.book);
  await mkdir(retired, { recursive: true });

  const oldPath = join(directory, "cases", args.book, `${args.idea}.yaml`);
  const oldCase = parse(await readFile(oldPath, "utf8")) as Record<
    string,
    unknown
  >;
  await writeFile(
    join(retired, `${args.idea}.yaml`),
    stringify({
      ...oldCase,
      retired: {
        on: today,
        reason: args.reason.trim() || "Rejected by the user",
      },
    }),
  );
  await rm(oldPath);

  await writeFile(
    join(directory, "cases", args.book, `${idea.id}.yaml`),
    stringify({
      schema_version: 1,
      purpose: `Replacement for ${args.idea}, rejected by the user on ${today}.`,
      source: `Generated by the eval rating page with ideas prompt v${PROMPT_VERSION}, ${today}`,
      idea,
    }),
  );

  const suitePath = join(directory, "suite.yaml");
  const suiteFile = parse(await readFile(suitePath, "utf8")) as {
    schema_version: number;
    suite_version: number;
    cases: { book: string; idea: string }[];
  };
  const cases = suiteFile.cases.map((entry) => {
    if (entry.book === args.book && entry.idea === args.idea) {
      return { book: args.book, idea: idea.id };
    }

    return entry;
  });
  await writeFile(
    suitePath,
    SUITE_HEADER +
      stringify({
        schema_version: suiteFile.schema_version,
        suite_version: suiteFile.suite_version + 1,
        cases,
      }),
  );

  // Confirms the edited suite still loads before reporting success.
  await loadSuite({
    directory,
    ...(args.registryPath ? { registryPath: args.registryPath } : {}),
  });

  return idea;
}

function rejectionReason(reason: string): string {
  if (reason.trim() === "") {
    return "";
  }

  return `\nThe user rejected the previous idea because: ${reason.trim()}\nAvoid that problem in the new idea.\n`;
}

async function collectResponse(
  events: ReturnType<IdeaGenerator>,
): Promise<string> {
  let response = "";
  let completed = false;

  for await (const event of events) {
    if (event.type === "turn.failed") {
      throw new Error(event.error.message);
    }

    if (event.type === "error") {
      throw new Error(event.message);
    }

    if (event.type === "turn.completed") {
      completed = true;
    }

    if (
      event.type === "item.completed" &&
      event.item.type === "agent_message"
    ) {
      response = event.item.text;
    }
  }

  if (!completed) {
    throw new Error("Codex stream ended without a completed turn");
  }

  return response;
}
